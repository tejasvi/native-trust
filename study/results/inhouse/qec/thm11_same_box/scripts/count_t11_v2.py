#!/usr/bin/env python3
"""Items 3 and 4 (read-only): hand-written vs generated Lean in the published QEC trees.
v2 of the script: the rule also counts the root modules QEC.lean and QECComp.lean (which reproduces the recorded
89 / 18,643 and 128 / 25,091), and the generator list is the release commit's (git ls-tree 9a639b4 gen/kernel), so a
stats script added after the release is not counted.
Trees: v2 = the native project at commit 643d947 (the v2 supplement's lean4/), v3 = the kernel track at release commit
9a639b4 (the v3 supplement's lean4/). Both working trees are clean for every .lean file and generator script relative to
those commits (checked with git status / git diff before this run), so files are read from the working trees.
Rule for hand-written (both trees' FORMALIZATION.md, line 3): the .lean files under QEC/ and QECComp/ (v3: also
QECKernel/), excluding the generated data modules QECComp/Data, the check directories QEC/Checks* and, in v3, the
generated kernel modules (the subdirectories of QECKernel/ other than Fin/, and QECKernel/AggTab.lean).
Theorem 1.1: import closures (project modules only) of QEC.Checks.Thm11V3 (kernel-only version) and QEC.ChecksN.Thm11V2
(native version) in v2; per closure module whether it is hand-written by the rule, in a check directory (generated by
gen/gen_checks.py or gen/gen_agg.py, except the two theorem files), or a data module. Lines = wc -l (newline count).
usage: count_t11_v1.py V2_TREE V3_TREE OUTDIR"""
import re, sys
from pathlib import Path

V2, V3, OUT = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]); OUT.mkdir(parents=True, exist_ok=True)
nl = lambda p: p.read_bytes().count(b'\n')


def leans(root, top):
    return sorted(p for p in (root / top).rglob('*.lean')) if (root / top).exists() else []


def handwritten(root, kernel=False):
    hw, gen = [r for r in ('QEC.lean', 'QECComp.lean') if (root / r).exists()], []
    for top in ('QEC', 'QECComp') + (('QECKernel',) if kernel else ()):
        for p in leans(root, top):
            r = p.relative_to(root).as_posix()
            g = (r.startswith('QECComp/Data/') or re.match(r'QEC/Checks[^/]*/', r) is not None or
                 (r.startswith('QECKernel/') and (r.count('/') >= 2 and not r.startswith('QECKernel/Fin/') or r == 'QECKernel/AggTab.lean')))
            (gen if g else hw).append(r)
    return hw, gen


def modfile(root, m):
    p = root / (m.replace('.', '/') + '.lean')
    return p if p.exists() else None


def closure(root, start):
    seen, todo = set(), [start]
    while todo:
        m = todo.pop()
        if m in seen:
            continue
        p = modfile(root, m)
        if p is None:
            continue           # outside the project (Mathlib, Std, Init)
        seen.add(m)
        for l in p.read_text(errors='ignore').splitlines():
            mm = re.match(r'\s*import\s+(\S+)', l)
            if mm:
                todo.append(mm.group(1))
    return seen


rep = []
# v2 and v3 hand-written counts by the rule
for name, root, k in (('v2', V2, False), ('v3', V3, True)):
    hw, gen = handwritten(root, k)
    rep.append(f"{name}: hand-written {len(hw)} files / {sum(nl(root / r) for r in hw)} lines; excluded as generated {len(gen)} files")
    if k:
        kh = [r for r in hw if r.startswith('QECKernel/')]
        nk = [r for r in hw if not r.startswith('QECKernel/')]
        (OUT / 'v3_handwritten_v2rule_part.tsv').write_text(''.join(f"{r}\t{nl(root / r)}\n" for r in nk))
        kg = [r for r in gen if r.startswith('QECKernel/')]
        rep.append(f"v3 kernel part: hand-written QECKernel files {len(kh)} / {sum(nl(root / r) for r in kh)} lines "
                   f"(top level {sum(1 for r in kh if r.count('/') == 1)}, Fin/ {sum(1 for r in kh if r.startswith('QECKernel/Fin/'))}); "
                   f"generated QECKernel files {len(kg)}; v2 rule part in v3: {len(nk)} / {sum(nl(root / r) for r in nk)} lines")
        (OUT / 'v3_kernel_handwritten.tsv').write_text(''.join(f"{r}\t{nl(root / r)}\n" for r in kh))
        import subprocess
        rel = subprocess.run(['git', '-C', str(root), 'ls-tree', '--name-only', '9a639b4', 'gen/kernel/'], capture_output=True, text=True, check=True).stdout.split()
        gens = sorted(root / r for r in rel if r.endswith('.py'))
        rep.append('v3 kernel generators: ' + ', '.join(f"gen/kernel/{p.name} {nl(p)}" for p in gens) +
                   f" (total {sum(nl(p) for p in gens)} lines)")
        sub = {}
        for r in kg:
            d = r.split('/')[1] if r.count('/') >= 2 else r
            sub[d] = sub.get(d, 0) + 1
        (OUT / 'v3_kernel_generated_by_dir.tsv').write_text(''.join(f"{d}\t{n}\n" for d, n in sorted(sub.items())))
# Theorem 1.1 closures in v2
K = closure(V2, 'QEC.Checks.Thm11V3'); N = closure(V2, 'QEC.ChecksN.Thm11V2')
hw2, _ = handwritten(V2)
hws = set(hw2)
def kind(m):
    r = m.replace('.', '/') + '.lean'
    if r in hws:
        return 'hand-written'
    if r in ('QEC/Checks/Thm11V3.lean', 'QEC/ChecksN/Thm11V2.lean'):
        return 'hand-written theorem file (in a check directory)'
    if r in ('QEC/Checks/AllK.lean', 'QEC/ChecksN/AllN.lean'):
        return 'generated aggregator (gen/gen_agg.py)'
    if r.startswith('QEC/Checks/') or r.startswith('QEC/ChecksN/'):
        return 'generated check module (gen/gen_checks.py)'
    if r.startswith('QECComp/Data/'):
        return 'generated data module'
    return 'other'
rows = []
for part, ms in (('kernel-only', K - N), ('shared', K & N), ('native-only', N - K)):
    for m in sorted(ms):
        rows.append((part, kind(m), m, nl(modfile(V2, m))))
(OUT / 'thm11_closure_v2.tsv').write_text('part\tkind\tmodule\tlines\n' + ''.join('\t'.join(map(str, r)) + '\n' for r in rows))
summ = {}
for part, kd, m, n in rows:
    a = summ.setdefault((part, kd), [0, 0]); a[0] += 1; a[1] += n
rep.append(f"Theorem 1.1 (v2, 643d947): closure of QEC.Checks.Thm11V3 {len(K)} project modules, of QEC.ChecksN.Thm11V2 {len(N)}")
for (part, kd), (c, n) in sorted(summ.items()):
    rep.append(f"  {part:12s} {kd:50s} {c:4d} files {n:7d} lines")
for g in ('gen/gen_checks.py', 'gen/gen_agg.py'):
    rep.append(f"  generator {g}: {nl(V2 / g)} lines")
(OUT / 'counts.txt').write_text('\n'.join(rep) + '\n')
print('\n'.join(rep))
